def _get(url: str, retries: int = 3, timeout: int = 60) -> dict:
    """带重试的 GET，返回 JSON。自动绕过本机代理。

    上游 RST 时不会快速失败，每个请求会挂满 timeout；retries=3 时最坏 190 秒。
    批量抓取前先单发一个请求探活，探不通就换路，别循环重试。
    """
    last = None
    for i in range(retries):
        try:
            req = urllib.request.Request(url, headers=UA)
            raw = OPENER.open(req, timeout=timeout).read()
            return json.loads(raw)
        except Exception as e:  # noqa: BLE001
            last = e
            if i + 1 < retries:
                time.sleep(1.5 * (i + 1))
    raise RuntimeError(f"请求失败 {url}: {last}")


def _bk(name: str) -> str:
    """把中文名 / BK 码统一成 BKxxxx。找不到就报错并给出模糊建议。

    老版本这里写的是 `BOARDS.get(name, name)`：名字不在表里就把中文原样当代码
    丢给东财，返回 null，最终报 `'NoneType' object is not subscriptable`。
    """
    s = name.strip().upper()
    if s.startswith("BK") and s[2:].isdigit():
        return s
    code = ALIASES.get(name) or BOARD_CODES.get(name)
    if code:
        return code
    near = [k for k in {**BOARD_CODES, **ALIASES} if name in k][:8]
    hint = f"；相近的有：{'、'.join(near)}" if near else "；用 `boards <关键词>` 搜"
    raise KeyError(f"未知板块「{name}」{hint}")


def _bk_fuzzy(kw: str) -> list[tuple[str, str, str]]:
    """按关键词模糊搜板块，返回 [(名称, 代码, 类别)]。"""
    out = []
    lower = kw.lower()
    for k, v in BOARD_CODES.items():
        if lower in k.lower():
            out.append((k, v, "行业" if k in INDUSTRY_CODES else "概念"))
    for k, v in ALIASES.items():
        if lower in k.lower():
            out.append((k, v, "别名"))
    return out


def _fetch_board_codes(timeout: int = 20) -> dict[str, str]:
    """从东财 clist 分页拉全量行业+概念板块代码。pz 给 500 也只回 100 条，必须翻页。"""
    out: dict[str, str] = {}
    for fs in ("m:90+t:2", "m:90+t:3"):
        for pn in range(1, 20):
            url = (
                "https://push2.eastmoney.com/api/qt/clist/get?"
                f"pn={pn}&pz=100&po=1&np=1&fltt=2&invt=2&fid=f62&fs={fs}&fields=f12,f14"
            )
            d = _get(url, retries=1, timeout=timeout)
            items = (d.get("data") or {}).get("diff") or []
            if not items:
                break
            for x in items:
                out.setdefault(x["f14"], x["f12"])
    return out


def _secid(code: str) -> str:
    """把 6 位代码转成东财 secid。"""
    if code.startswith(("60", "68", "90", "5")):
        return f"1.{code}"
    return f"0.{code}"


def quote(code: str) -> dict:
    """个股快照。pe/pb 已 /100，可直接用；mcap 单位元。"""
    url = (
        "https://push2.eastmoney.com/api/qt/stock/get"
        f"?secid={_secid(code)}&fields=f43,f57,f58,f116,f162,f167,f168,f170"
    )
    d = _get(url)["data"]
    if not d:
        raise ValueError(f"{code} 无数据")
    return {
        "code": d.get("f57"),
        "name": d.get("f58"),
        "px": (d.get("f43") or 0) / 100,
        "mcap": d.get("f116") or 0,
        "pe_static": (d.get("f162") or 0) / 100,
        "pb": (d.get("f167") or 0) / 100,
        "turnover": (d.get("f168") or 0) / 100,
        "chg_pct": (d.get("f170") or 0) / 100,
    }


def board_kline(name: str, days: int = 250) -> list[tuple[str, float]]:
    """板块日线（收盘价）。name 可以是中文名（全量 1049 个）或直接 BK 码。"""
    bk = _bk(name)
    url = (
        "https://push2his.eastmoney.com/api/qt/stock/kline/get"
        f"?secid=90.{bk}&fields1=f1,f2,f3&fields2=f51,f53&klt=101&fqt=1"
        f"&end=20500101&lmt={days}"
    )
    d = _get(url, timeout=15)["data"]
    if not d or not d.get("klines"):
        raise ValueError(f"{name}({bk}) 无K线数据，代码可能已下架")
    return [(x.split(",")[0], float(x.split(",")[1])) for x in d["klines"]]


def board_flow(name: str) -> dict:
    """板块资金流：今日主力净额 + 5/20/60 日累计（单位亿）。"""
    bk = _bk(name)
    url = (
        "https://push2his.eastmoney.com/api/qt/stock/fflow/daykline/get"
        f"?secid=90.{bk}&fields1=f1,f2,f3,f7&fields2=f51,f52,f53,f54,f55,f56,f57,f58,f59,f60,f61"
    )
    d = _get(url, timeout=15)["data"]
    if not d or not d.get("klines"):
        raise ValueError(f"{name}({bk}) 无资金流数据，代码可能已下架")
    k = d["klines"]
    # 每行: 日期,主力净额,小单,中单,大单,超大单
    main = [float(x.split(",")[1]) for x in k]

    def s(n: int) -> float:
        return round(sum(main[-n:]) / 1e8, 1) if len(main) >= n else float("nan")

    return {"name": name, "today": s(1), "5d": s(5), "20d": s(20), "60d": s(60)}


def fin_period(report_date: str) -> list[dict]:
    """全市场单期财报（营收/净利/同比/毛利率）。report_date 形如 2026-09-30。"""
    out, page = [], 1
    cols = (
        "SECURITY_CODE,SECURITY_NAME_ABBR,TOTAL_OPERATE_INCOME,YSTZ,"
        "PARENT_NETPROFIT,SJLTZ,XSMLL,BOARD_NAME,REPORTDATE"
    )
    while True:
        q = dict(
            reportName="RPT_LICO_FN_CPD", columns=cols, pageSize=500,
            sortColumns="SECURITY_CODE", sortTypes="1", source="WEB",
            client="WEB", pageNumber=page, filter=f"(REPORTDATE='{report_date}')",
        )
        d = _get("https://datacenter-web.eastmoney.com/api/data/v1/get?" + urllib.parse.urlencode(q))
        r = d.get("result")
        if not r:
            if page == 1:
                print(f"[warn] {report_date} 无数据: {d.get('code')} {d.get('message')}", file=sys.stderr)
            break
        out += r["data"]
        if page >= r["pages"]:
            break
        page += 1
        time.sleep(0.15)
    return out


def _stmt(report_name: str, report_date: str, cols: str) -> list[dict]:
    """通用报表拉取（现金流/资产负债）。注意 filter 用 REPORT_DATE 且带时分秒。"""
    out, page = [], 1
    while True:
        q = dict(
            reportName=report_name, columns=cols, pageSize=500,
            sortColumns="SECURITY_CODE", sortTypes="1", source="WEB",
            client="WEB", pageNumber=page,
            filter=f"(REPORT_DATE='{report_date} 00:00:00')",
        )
        d = _get("https://datacenter-web.eastmoney.com/api/data/v1/get?" + urllib.parse.urlencode(q))
        r = d.get("result")
        if not r:
            if page == 1:
                print(f"[warn] {report_name} {report_date}: {d.get('code')} {d.get('message')}", file=sys.stderr)
            break
        out += r["data"]
        if page >= r["pages"]:
            break
        page += 1
        time.sleep(0.15)
    return out


def cashflow(report_date: str) -> list[dict]:
    return _stmt("RPT_DMSK_FN_CASHFLOW", report_date,
                 "SECURITY_CODE,NETCASH_OPERATE,SALES_SERVICES")


def balance(report_date: str) -> list[dict]:
    return _stmt("RPT_DMSK_FN_BALANCE", report_date,
                 "SECURITY_CODE,ACCOUNTS_RECE,INVENTORY,TOTAL_ASSETS,TOTAL_LIABILITIES,TOTAL_EQUITY")


def _dump(obj, out: str | None) -> None:
    if out:
        p = Path(out)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(obj, ensure_ascii=False), encoding="utf-8")
        print(f"-> {p}")
    else:
        print(json.dumps(obj, ensure_ascii=False, indent=1)[:4000])


def main() -> None:
    ap = argparse.ArgumentParser(description="东方财富数据抓取（自动绕过本机代理）")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("quote", help="个股快照")
    p.add_argument("codes", nargs="+")

    p = sub.add_parser("board", help="板块日线")
    p.add_argument("names", nargs="+", help="中文名（全量 1049 个）或 BK 码")
    p.add_argument("--days", type=int, default=250)

    p = sub.add_parser("flow", help="板块资金流")
    p.add_argument("names", nargs="+", help="中文名或 BK 码")

    p = sub.add_parser("fin", help="全市场单期财报")
    p.add_argument("date", help="2026-09-30")
    p.add_argument("--out")

    p = sub.add_parser("cashflow", help="全市场现金流量表")
    p.add_argument("date")
    p.add_argument("--out")

    p = sub.add_parser("balance", help="全市场资产负债表")
    p.add_argument("date")
    p.add_argument("--out")

    p = sub.add_parser("boards", help="搜板块代码；不带参数列出常用别名")
    p.add_argument("kw", nargs="*", help="关键词，模糊匹配")
    p.add_argument("--refresh", action="store_true",
                   help="重拉东财全量板块码，对比本地表差异（不自动写回）")
    p.add_argument("--all", action="store_true", help="列出全量 1049 个")

    a = ap.parse_args()

    if a.cmd == "quote":
        for c in a.codes:
            q = quote(c)
            print(f"{q['code']} {q['name']:<8} 现价{q['px']:>8.2f} "
                  f"市值{q['mcap']/1e8:>8.0f}亿 PE25A {q['pe_static']:>6.1f} PB {q['pb']:>5.2f}")
    elif a.cmd == "board":
        for n in a.names:
            k = board_kline(n, a.days)
            cur = k[-1][1]
            hi = max(k, key=lambda x: x[1])
            print(f"{n:<10} {k[-1][0]} 收{cur:>10.2f} 区间高{hi[1]:>10.2f}({hi[0]}) 距高{(cur/hi[1]-1)*100:+.1f}%")
    elif a.cmd == "flow":
        for n in a.names:
            f = board_flow(n)
            print(f"{n:<10} 今日{f['today']:>9.1f}亿  5日{f['5d']:>9.1f}  20日{f['20d']:>9.1f}  60日{f['60d']:>9.1f}")
